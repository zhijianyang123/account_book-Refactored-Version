import 'package:flutter/widgets.dart';

/// Lightweight zh/en lookup used across the app.
class AppLocalizations {
  const AppLocalizations(this.locale);

  final Locale locale;

  static AppLocalizations of(BuildContext context) =>
      Localizations.of<AppLocalizations>(context, AppLocalizations) ??
      const AppLocalizations(Locale('zh'));

  static const LocalizationsDelegate<AppLocalizations> delegate =
      _AppLocalizationsDelegate();

  static const List<Locale> supportedLocales = [
    Locale('zh'),
    Locale('en'),
  ];

  String get languageCode => locale.languageCode;

  String t(String key) {
    final table = _strings[locale.languageCode] ?? _strings['zh']!;
    return table[key] ?? _strings['zh']![key] ?? key;
  }

  String tArgs(String key, Map<String, Object> args) {
    var text = t(key);
    args.forEach((name, value) {
      text = text.replaceAll('{$name}', '$value');
    });
    return text;
  }

  static const Map<String, String> _defaultCategoryEn = {
    '餐饮': 'Dining',
    '交通': 'Transport',
    '购物': 'Shopping',
    '居家': 'Home',
    '娱乐': 'Entertainment',
    '医疗': 'Medical',
    '工资': 'Salary',
    '奖金': 'Bonus',
    '理财': 'Investment',
    '其他收入': 'Other income',
  };

  /// Localizes the seeded default category names. Custom names pass through.
  String categoryName(String name) =>
      locale.languageCode == 'en' ? (_defaultCategoryEn[name] ?? name) : name;
}

class _AppLocalizationsDelegate
    extends LocalizationsDelegate<AppLocalizations> {
  const _AppLocalizationsDelegate();

  @override
  bool isSupported(Locale locale) =>
      AppLocalizations.supportedLocales
          .any((l) => l.languageCode == locale.languageCode);

  @override
  Future<AppLocalizations> load(Locale locale) async =>
      AppLocalizations(locale);

  @override
  bool shouldReload(_AppLocalizationsDelegate old) => false;
}

